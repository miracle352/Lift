/**
 * Generates the hero landscape geometry (src/components/marketing/landscape-paths.ts).
 * Deterministic (seeded). Run: pnpm tsx scripts/gen-landscape.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const W = 1600;
const H = 900;
type P = readonly [number, number];

function rng(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Ridge = pointed peak envelopes + midpoint-displacement detail (more detail on bigger amplitudes). */
function ridge(o: { seed: number; base: number; amp: number; rough: number; peaks: Array<[cx: number, h: number, w: number]>; steps?: number; sharp?: number }): P[] {
  const r = rng(o.seed);
  const n = o.steps ?? 256;
  const size = 2 ** Math.ceil(Math.log2(n));
  const pts = new Array(size + 1).fill(0);
  let disp = o.amp;
  for (let s = size; s > 1; s /= 2) {
    for (let i = s / 2; i < size; i += s) pts[i] = (pts[i - s / 2] + pts[i + s / 2]) / 2 + (r() * 2 - 1) * disp;
    disp *= o.rough;
  }
  const sharp = o.sharp ?? 1.25;
  // rugged shoulders: smaller random sub-peaks around each main peak
  const peaks: Array<[number, number, number]> = [...o.peaks];
  for (const [cx, h, w] of o.peaks) {
    for (let k = 0; k < 4; k++) {
      const off = (r() * 2 - 1) * w * 0.8;
      peaks.push([cx + off, h * (0.35 + r() * 0.45) * (1 - Math.abs(off) / (w * 1.2)), w * (0.18 + r() * 0.22)]);
    }
  }
  return pts.map((y, i) => {
    const x = (i / size) * W;
    let env = 0;
    for (const [cx, h, w] of peaks) env = Math.max(env, h * Math.max(0, 1 - Math.abs(x - cx) / w) ** sharp);
    return [x, o.base - env + y * (0.35 + env / 160)] as const;
  });
}

const f = (n: number) => String(Math.round(n));
const fill = (pts: P[]) => `M0 ${H}L` + pts.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + `L${W} ${H}Z`;
const crest = (pts: P[], from: number, to: number) => 'M' + pts.filter(([x]) => x >= from && x <= to).map(([x, y]) => `${f(x)} ${f(y + 0.5)}`).join('L');

const far = ridge({ seed: 11, base: 545, amp: 22, rough: 0.58, peaks: [[160, 250, 300], [470, 120, 210], [1120, 230, 260], [1430, 330, 230]] });
const mid = ridge({ seed: 23, base: 600, amp: 26, rough: 0.6, peaks: [[60, 170, 260], [360, 90, 220], [930, 60, 200], [1290, 190, 260], [1600, 160, 200]] });
const near = ridge({ seed: 37, base: 668, amp: 24, rough: 0.62, peaks: [[0, 150, 330], [300, 70, 230], [1180, 90, 240], [1560, 170, 260]], sharp: 1.4 });
const frontRaw = ridge({ seed: 53, base: 840, amp: 16, rough: 0.7, peaks: [[0, 190, 520], [260, 90, 280], [1340, 110, 300], [1600, 220, 520]], steps: 512, sharp: 1.2 });
// tree line: thin spikes on the foreground silhouette
const tr = rng(99);
const front = frontRaw.map(([x, y], i) => [x, y - (i % 2 ? 4 + tr() * 16 : 0)] as const);

// River centerline from the far valley to the viewer; width grows with perspective.
const ctrl: P[] = [[812, 640], [836, 656], [790, 672], [818, 690], [900, 712], [850, 738], [728, 764], [770, 800], [930, 838], [860, 876], [690, 914]];
function catmull(points: P[], seg = 14): P[] {
  const out: P[] = [];
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[Math.max(0, i - 1)], p1 = points[i], p2 = points[i + 1], p3 = points[Math.min(points.length - 1, i + 2)];
    for (let t = 0; t < seg; t++) {
      const u = t / seg, u2 = u * u, u3 = u2 * u;
      out.push([
        0.5 * (2 * p1[0] + (-p0[0] + p2[0]) * u + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * u2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * u3),
        0.5 * (2 * p1[1] + (-p0[1] + p2[1]) * u + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * u2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * u3),
      ]);
    }
  }
  out.push(points[points.length - 1]);
  return out;
}
const center = catmull(ctrl);
const width = (y: number) => 1.2 + ((y - 640) / (912 - 640)) ** 1.9 * 34;
const left: P[] = [], right: P[] = [];
center.forEach((p, i) => {
  const a = center[Math.max(0, i - 1)], b = center[Math.min(center.length - 1, i + 1)];
  const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy) || 1;
  const nx = -dy / len, ny = dx / len, w = width(p[1]) / 2;
  left.push([p[0] + nx * w, p[1] + ny * w]);
  right.push([p[0] - nx * w, p[1] - ny * w]);
});
const riverFill = 'M' + left.map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + 'L' + right.reverse().map(([x, y]) => `${f(x)} ${f(y)}`).join('L') + 'Z';
const riverLine = 'M' + center.map(([x, y]) => `${f(x)} ${f(y)}`).join('L');

const out = `// Generated by scripts/gen-landscape.ts — do not edit by hand.
export const VIEW = { w: ${W}, h: ${H} } as const;
export const RIDGE_FAR = '${fill(far)}';
export const RIDGE_MID = '${fill(mid)}';
export const RIDGE_NEAR = '${fill(near)}';
export const RIDGE_FRONT = '${fill(front)}';
/** Sun-facing crest lines that light up. */
export const GLOW_FAR_R = '${crest(far, 1010, 1600)}';
export const GLOW_FAR_L = '${crest(far, 0, 330)}';
export const GLOW_MID_R = '${crest(mid, 1100, 1480)}';
export const RIVER_FILL = '${riverFill}';
export const RIVER_LINE = '${riverLine}';
`;
writeFileSync(join(__dirname, '..', 'src', 'components', 'marketing', 'landscape-paths.ts'), out);
console.log('ok', out.length, 'bytes');
